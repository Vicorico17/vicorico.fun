test('Arabic translates the site, supports RTL and switches back to English', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  const nav = page.locator('.nimbus-nav')
  await nav.getByRole('button', { name: 'English' }).click()
  await page.locator('#liquid-language-options').getByRole('button', { name: 'العربية' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'ar')
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  await expect(page.locator('.portal-explore')).toHaveText('يلا نستكشف! ↓')
  await expect(page.locator('#projects-title')).toHaveText('مشاريع مختارة')
  await expect(nav.getByRole('button', { name: 'المظهر' })).toBeVisible()
  const box = await nav.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(375)
  await nav.getByRole('button', { name: 'العربية' }).press('ArrowLeft')
  await expect(nav.getByRole('button', { name: 'المظهر' })).toBeFocused()
  await nav.getByRole('button', { name: 'المظهر' }).click()
  await page.locator('#liquid-theme-options').getByRole('button', { name: 'ورق' }).click()
  await expect(nav).toHaveAttribute('data-tone', 'light')
  await page.screenshot({ path: 'output/navbar-arabic.png' })
  await nav.getByRole('button', { name: 'العربية' }).click()
  await page.locator('#liquid-language-options').getByRole('button', { name: 'English' }).click()
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr')
  await expect(page.locator('.portal-explore')).toHaveText('EXPLORE ↓')
  await expect(page.locator('#projects-title')).toHaveText('Selected Projects')
})
