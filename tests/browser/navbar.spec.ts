import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('https://**/*', route => route.abort())
})

test('liquid menu opens existing language and theme controls without PDF', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const nav = page.locator('.nimbus-nav')
  await expect(nav).toBeVisible()
  await expect(page.locator('.portal-nav')).toBeHidden()
  await expect(nav.locator('.nimbus-item')).toHaveCount(3)
  await expect(nav.getByRole('link', { name: 'PDF CV' })).toHaveCount(0)
  await expect(nav.getByRole('link', { name: 'Vico’s Quest' })).toHaveAttribute('href', 'game.html')
  await nav.getByRole('button', { name: 'Themes' }).click()
  await page.locator('#liquid-theme-options').getByRole('button', { name: 'Paper' }).click()
  await expect(nav).toHaveAttribute('data-tone', 'light')
  await expect(page.locator('#liquid-theme-options')).toBeHidden()
  await nav.getByRole('button', { name: 'English' }).click()
  await page.locator('#liquid-language-options').getByRole('button', { name: 'Română' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'ro')
  await expect(nav.getByRole('button', { name: 'Română' })).toBeVisible()
  await expect(page.locator('#liquid-language-options')).toBeHidden()
  await nav.getByRole('button', { name: 'Română' }).click()
  await expect(page.locator('#liquid-language-options')).toBeVisible()
  await nav.getByRole('button', { name: 'Română' }).click()
  await expect(page.locator('#liquid-language-options')).toBeHidden()
  await nav.getByRole('button', { name: 'Română' }).press('ArrowDown')
  await expect(page.locator('#liquid-language-options button').first()).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(nav.getByRole('button', { name: 'Română' })).toBeFocused()
  await expect(page.locator('#liquid-language-options')).toBeHidden()
  await expect.poll(() => errors).toEqual([])
})

test('mobile labels and popup fit and Quest opens the game', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  const nav = page.locator('.nimbus-nav')
  await expect(nav).toBeVisible()
  const bounds = await nav.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(375)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(812)
  await nav.getByRole('button', { name: 'English' }).click()
  const panel = page.locator('#liquid-language-options')
  await expect(panel).toBeVisible()
  const box = await panel.boundingBox()
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(375)
  await page.screenshot({ path: 'output/navbar-mobile.png' })
  await page.locator('h1').click()
  await expect(panel).toBeHidden()
  await nav.getByRole('link', { name: 'Vico’s Quest' }).click()
  await expect(page).toHaveURL(/game.html$/)
})

test('CSS fallback and reduced motion work without WebGL', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function (type: string, ...args: unknown[]) {
      if (type === 'webgl' || type === 'webgl2') return null
      return original.call(this, type as '2d', ...args)
    } as typeof original
  })
  await page.goto('/navbar-demo.html')
  const nav = page.locator('.nimbus-nav')
  await expect(nav).toHaveAttribute('data-gl', 'off')
  await nav.getByRole('button', { name: 'Profile' }).click()
  await expect(nav.getByRole('button', { name: 'Profile' })).toHaveAttribute('aria-current', 'page')
  const drop = nav.locator('.nimbus-drop')
  await expect(drop).toBeVisible()
  await expect.poll(async () => {
    const a = await drop.boundingBox(), b = await nav.getByRole('button', { name: 'Profile' }).boundingBox()
    return Math.abs(a!.x - b!.x)
  }).toBeLessThan(2)
  await page.screenshot({ path: 'output/navbar-fallback.png' })
})

